// dist/app.js + dist/app.css → ../cli/src/console/ui.gen.ts (strings the CLI serves; JSR ships them).
import { readFileSync, writeFileSync } from 'node:fs';
const js = readFileSync(new URL('./dist/app.js', import.meta.url), 'utf8');
const css = readFileSync(new URL('./dist/app.css', import.meta.url), 'utf8');
const out = `// Generated by packages/console-ui (npm run build -w @icebase/console-ui). Do not edit.\nexport const UI_JS: string = ${JSON.stringify(js)};\nexport const UI_CSS: string = ${JSON.stringify(css)};\n`;
writeFileSync(new URL('../cli/src/console/ui.gen.ts', import.meta.url), out);
console.log(`ui.gen.ts: js ${(js.length / 1024).toFixed(0)} KB, css ${(css.length / 1024).toFixed(0)} KB`);
